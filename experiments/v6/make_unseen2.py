"""Build ycode/lm/unseen2.py (unseen-v2) from independently written candidates.

The candidates (experiments/v6/unseen_v2_candidates.py) were written by a separate agent that did
not read this repository, before the V6 curriculum data was built. This script keeps a candidate
only if the starting checkpoint never trained on it in any form, judged automatically:

* its name is not a training-generator name or another held-out item's name;
* no training function (v5 generators: concepts, compositions, novel and skill exercises with
  their loop renderings) and no other held-out reference has the same AST skeleton
  (``leakage.skeleton``: same code up to names, constants, operators, min/max, ...);
* no such function passes its tests and agrees with its reference on >= 90% of probe inputs.

The V6 curriculum is NOT used here: it must give way to this set (``idioms.held_out_check`` drops
curriculum programs that match an unseen-v2 item), not the other way round.
Only counts are printed, so the set can be built without reading its tasks.

usage: python experiments/v6/make_unseen2.py
"""
import ast
import copy
import importlib.util
import signal
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import ycode.lm.compose as compose  # noqa: E402
from ycode.lm.basics import CONCEPTS, _passes  # noqa: E402
from ycode.lm.leakage import HeldOutItem, _arity, agreement, held_out_items, probe_inputs, skeleton  # noqa: E402

spec = importlib.util.spec_from_file_location("cands", ROOT / "experiments/v6/unseen_v2_candidates.py")
cands = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cands)


def source(name, sig, body):
    return f"def {sig}:\n" + "\n".join("    " + line for line in body.splitlines())


items, tasks = [], {}
for name, sig, task, body, tests in cands._TASKS:
    ref = source(name, sig, body)
    assert _passes(ref, tests, timeout=2.0), name
    items.append(HeldOutItem("unseen2", name, _arity(sig.split("(", 1)[1].rstrip(")")), tests, ref))
    tasks[name] = (name, sig, task, body, tests)

# the starting checkpoint's training functions (as in experiments/v51/check_unseen.py)
saved = compose.INCLUDE_SKILLS
compose.INCLUDE_SKILLS = True
names = {n for c in CONCEPTS for n in (c.name, *c.aliases)}
fns = {}
for c in CONCEPTS:
    for n in (c.name, *c.aliases):
        fns[c.source(n)] = (n, _arity(c.params))
for seed in (7, 1055, 1101, 1201, 1202, 1203, 1301, 1302):
    for e in compose._raw_exercises(seed) + compose.novel_exercises(seed) + compose.skill_exercises():
        names.add(e.name)
        for x in (e, compose.loop_rendering(e)):
            if x is not None:
                fns[x.source()] = (x.name, _arity(x.params))
compose.INCLUDE_SKILLS = saved
for i in held_out_items():  # bench, dev, unseen-v1
    fns[i.reference] = (f"{i.split}:{i.name}", i.arity)
    names.add(i.name)
train_skeletons = {skeleton(src) for src in fns}


def alarm(*_):
    raise TimeoutError


signal.signal(signal.SIGALRM, alarm)


def call(f, args, t=0.05):
    signal.setitimer(signal.ITIMER_REAL, t)
    try:
        return ("ok", repr(f(*copy.deepcopy(args))))
    except BaseException as e:  # noqa: BLE001
        return ("err", type(e).__name__)
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)


def first_call(item):
    for node in ast.walk(ast.parse(item.tests)):
        if isinstance(node, ast.Call) and getattr(node.func, "id", None) == item.name:
            return tuple(ast.literal_eval(a) for a in node.args)


reasons = {}
for it in items:
    if it.name in names:
        reasons[it.name] = "name"
    elif skeleton(it.reference) in train_skeletons:
        reasons[it.name] = "skeleton"
compiled = []
for src, (fname, ar) in fns.items():
    ns = {}
    defined = src.split("def ", 1)[1].split("(", 1)[0].strip()
    try:
        signal.setitimer(signal.ITIMER_REAL, 0.5)
        exec(src, ns)
        signal.setitimer(signal.ITIMER_REAL, 0)
        compiled.append((src, defined, ar, ns[defined]))
    except BaseException:  # noqa: BLE001
        signal.setitimer(signal.ITIMER_REAL, 0)
for it in items:
    if it.name in reasons:
        continue
    ns = {}
    exec(it.reference, ns)
    args = first_call(it)
    expected = call(ns[it.name], args, 1.0)
    for src, defined, ar, f in compiled:
        if ar != it.arity or call(f, args) != expected:
            continue
        if _passes(f"{src}\n\n{it.name} = {defined}", it.tests, timeout=0.5) and \
                agreement(src, defined, it, probe_inputs(it), isolate=True) >= 0.9:
            reasons[it.name] = "behaviour"
            break

kept = [tasks[i.name] for i in items if i.name not in reasons]
lines = ['"""Unseen-concept test set v2 (generated by experiments/v6/make_unseen2.py: do not edit by hand).', "",
         "Written by a separate agent that did not read this repository, before the V6 curriculum was built;",
         f"{len(items)} candidates, {len(items) - len(kept)} dropped because the starting checkpoint trained on them in some form",
         f"(by reason: {dict(Counter(reasons.values()))}). Held out of every generator like unseen-v1.", '"""', "",
         "from __future__ import annotations", "", "from ycode.lm.evaluate import Problem", "",
         'UNSEEN2_VERSION = "unseen-v2"', "", "_TASKS: tuple[tuple[str, str, str, str, str], ...] = ("]
lines += [f"    {t!r}," for t in kept]
lines += [")", "", "", "def _source(sig: str, body: str) -> str:",
          '    return f"def {sig}:\\n" + "\\n".join("    " + line for line in body.splitlines())', "", "",
          "def unseen2_problems() -> tuple[Problem, ...]:",
          '    return tuple(Problem(name, f"Write a Python function `{sig}` that {task}", tests) for name, sig, task, _b, tests in _TASKS)',
          "", "", "def unseen2_references() -> dict[str, str]:",
          "    return {name: _source(sig, body) for name, sig, _task, body, _tests in _TASKS}", "", "",
          "def unseen2_names() -> set[str]:", "    return {t[0] for t in _TASKS}", ""]
(ROOT / "ycode/lm/unseen2.py").write_text("\n".join(lines))
print(f"candidates {len(items)}, kept {len(kept)}, dropped {dict(Counter(reasons.values()))}")
