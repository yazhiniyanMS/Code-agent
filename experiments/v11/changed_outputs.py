"""V11: the exact outputs of every dev and unseen-v1 item a candidate changed against round 54.

usage: changed_outputs.py OUT.md [MODEL ...]     (MODEL names as in experiments/v11/compare.py; default all)

For each candidate, every item whose pass/fail differs from round 54's (lost or gained), with the prompt,
round 54's extracted code and the candidate's, and whether the item is clean (not contaminated).
Read-only: reads the saved answer records, generates nothing.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))


def rows(path: Path) -> dict:
    return {f"{r['suite']}:{r['name']}": r for r in map(json.loads, path.read_text().splitlines())}


def main() -> None:
    import importlib.util

    spec = importlib.util.spec_from_file_location("v11_compare", ROOT / "experiments" / "v11" / "compare.py")
    cmp = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(cmp)
    ms = cmp.models()
    out_path, wanted = Path(sys.argv[1]), set(sys.argv[2:])
    base = ms[0]
    ref = next(m for m in ms if m["name"] == "R1 1301")["rec"]
    lines = ["# Changed outputs against round 54 (dev and unseen-v1)", "",
             "Generated by `experiments/v11/changed_outputs.py` from the saved answer records (greedy decoding).",
             "`clean`: the item is not in the record's contamination list; only clean items count for selection.", ""]
    for m in ms[1:]:
        if wanted and m["name"] not in wanted:
            continue
        lines += [f"## {m['name']}", ""]
        for which in ("dev", "unseen"):
            dirty = set(ref[which].get("contaminated", []))
            b, c = rows(base["dir"] / f"{which}.jsonl"), rows(m["dir"] / f"{which}.jsonl")
            for key in sorted(b):
                if key not in c or bool(b[key]["pass"]) == bool(c[key]["pass"]):
                    continue
                how = "LOST" if b[key]["pass"] else "gained"
                clean = "clean" if key not in dirty else "contaminated"
                lines += [f"### {which}:{key} - {how} ({clean})", "", f"Prompt: {b[key]['prompt']!r}", "",
                          "Round 54" + (" (passes):" if b[key]["pass"] else " (fails):"), "",
                          "```python", (b[key].get("code") or b[key].get("answer") or "").rstrip(), "```", "",
                          m["name"] + (" (passes):" if c[key]["pass"] else " (fails):"), "",
                          "```python", (c[key].get("code") or c[key].get("answer") or "").rstrip(), "```", ""]
    out_path.write_text("\n".join(lines))
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
