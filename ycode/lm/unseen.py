def _source(name: str, sig: str, body: str) -> str:
    return f"def {sig}:\n" + "\n".join("    " + line for line in body.splitlines())


def unseen_problems() -> tuple[Problem, ...]:
    """The unseen-concept problems, in the benchmark's prompt format."""
    return tuple(Problem(name, f"Write a Python function `{sig}` that {task}", tests)
                 for name, sig, task, _body, tests in _TASKS)


def unseen_references() -> dict[str, str]:
    """Reference solution of each unseen problem (evaluation only)."""
    return {name: _source(name, sig, body) for name, sig, _task, body, _tests in _TASKS}


def unseen_names() -> set[str]:
    return {t[0] for t in _TASKS}
