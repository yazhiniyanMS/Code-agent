"""Unseen-concept test set (version unseen-v1): programming tasks no training generator produces.

The dev set (``ycode.lm.devset``) holds concepts one slot word away from trained ones, and after
removing the items the v5 checkpoints saw in equivalent form it has 44 items: too few to tell a
3-point change from seed noise. These tasks add concepts of the same size and style that appear
nowhere in training, by name or by behaviour:

* their names are held out of every generator (``basics.held_out_names``);
* ``leakage.held_out_items`` includes them, so the build-time check removes any training answer
  that computes one of them, and ``tests/test_v51.py`` checks every generator against them.

Unlike several benchmark items, every task here has several assertions including edge cases, so a
near-miss implementation does not pass. Like the dev set, they are never trained on and are used to
choose between experiment arms; the benchmark is only reported.
"""

